CROSS JOIN (
    SELECT 'X-Bacon' AS nome, 1 AS quantidade
    UNION ALL
    SELECT 'Refrigerante Lata', 2
) v
JOIN produtos pr ON pr.nome = v.nome
WHERE p.id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM itens_pedido i WHERE i.pedido_id = p.id
  );

